/* ---------- i18n 引擎 ---------- */

function getLanguage() {
  try {
    const saved = localStorage.getItem(I18N_STORAGE_KEY);
    if (saved && I18N[saved]) return saved;
  } catch (error) { /* localStorage 不可用时回退 */ }
  return "zh";
}

function setLanguage(code) {
  if (!I18N[code]) return;
  try { localStorage.setItem(I18N_STORAGE_KEY, code); } catch (error) { /* 忽略 */ }
  document.documentElement.setAttribute("lang", code === "zh" ? "zh-CN" : code);
  document.title = t("meta.title");
  applyI18n();
}

function t(key, vars) {
  const dict = I18N[getLanguage()] || I18N.zh;
  let text = dict[key];
  if (text === undefined) text = I18N.zh[key];
  if (text === undefined) return key;
  if (vars) {
    Object.keys(vars).forEach((name) => {
      text = text.split("{" + name + "}").join(String(vars[name]));
    });
  }
  return text;
}

function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = t(el.getAttribute("data-i18n"));
    if (el.dataset.i18nAttr) {
      el.setAttribute(el.dataset.i18nAttr, value);
    } else {
      el.textContent = value;
    }
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  scope.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  scope.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    el.setAttribute("alt", t(el.getAttribute("data-i18n-alt")));
  });
}

